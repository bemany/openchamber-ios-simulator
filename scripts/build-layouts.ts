// Regenerates src/service/layouts.generated.ts from macOS's own keyboard
// layouts (scripts/macos-layouts.swift, Apple ISO keyboard type). Run on a Mac
// after adding a layout there; the result is committed, the service never runs Swift.
//
//   bun scripts/build-layouts.ts
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const json = execFileSync('swift', [resolve(root, 'scripts/macos-layouts.swift'), '41'], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
const layouts = JSON.parse(json) as Record<string, Record<string, number[][]>>;

/** One stroke as decimal usage, plus `s` for Shift and `a` for Option: "4", "31s", "15a". */
const stroke = ([usage, shift, option]: number[]) => `${usage}${shift ? 's' : ''}${option ? 'a' : ''}`;

const lines = Object.keys(layouts)
  .sort()
  .map((name) => {
    const table = layouts[name]!;
    const entries = Object.keys(table)
      .sort()
      .map((char) => `${JSON.stringify(char)}:${JSON.stringify(table[char]!.map(stroke).join(' '))}`);
    return `  ${name}: {${entries.join(',')}},`;
  });

writeFileSync(
  resolve(root, 'src/service/layouts.generated.ts'),
  `// Generated by scripts/build-layouts.ts from macOS's keyboard layouts (Apple ISO). Do not edit.
// Each character maps to its key strokes, separated by spaces: decimal HID usage,
// then "s" for Shift and "a" for Option. Two strokes are a dead key and the key after it.
export const LAYOUT_STROKES = {
${lines.join('\n')}
} as const;
`,
);
console.log(`Wrote ${Object.keys(layouts).length} layouts`);
